"use client";

import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import colleges from "./college";
import branches from "./branch";

// ---------- Types (match action/results.ts transforms) ----------
export type SubjectData = {
  name: string;
  internal: string;
  external: string;
  total: string;
  grade: string;
  credits: string;
  rcrv?: boolean;
};

export type AcademicData = {
  Details: { NAME: string; Roll_No: string; FATHER_NAME: string; COLLEGE_CODE: string };
  Semesters: Record<
    string,
    {
      Result: Record<string, SubjectData>;
      SGPA: number | string;
      Failed_Subjects?: string[];
      History?: Array<{ type: string }>;
    }
  >;
  CGPA: number | string;
};

export type SemesterData = {
  Details: { NAME: string; Roll_No: string; FATHER_NAME: string; COLLEGE_CODE: string };
  Result: Record<string, SubjectData>;
  SGPA: string | number;
};

export type AllResultData = {
  Details: { NAME: string; Roll_No: string; FATHER_NAME: string; COLLEGE_CODE: string; Regulation?: string };
  Results: Record<string, Array<{ exam_code: string; type: string; Result: Record<string, SubjectData> }>>;
};

// ---------- Helpers ----------
function gradeOf(g: string): string {
  const u = (g || "").toUpperCase();
  if (u === "A_PLUS") return "A+";
  return u;
}

function isPass(g: string): boolean {
  const u = gradeOf(g);
  return u !== "F" && u !== "AB";
}

function sortSemKeys(keys: string[]): string[] {
  return [...keys].sort((a, b) => {
    const [ay, as_] = a.split("-").map(Number);
    const [by, bs_] = b.split("-").map(Number);
    if (ay !== by) return ay - by;
    return as_ - bs_;
  });
}

const SEM_LABEL: Record<string, string> = {
  "1-1": "I-I", "1-2": "I-II", "2-1": "II-I", "2-2": "II-II",
  "3-1": "III-I", "3-2": "III-II", "4-1": "IV-I", "4-2": "IV-II",
};

const YEAR_SEMS: Array<[string, string]> = [["1-1", "1-2"], ["2-1", "2-2"], ["3-1", "3-2"], ["4-1", "4-2"]];
const YEAR_LABEL: Record<string, string> = { "1": "I YEAR", "2": "II YEAR", "3": "III YEAR", "4": "IV YEAR" };

function getAwardClass(cgpa: number, hasFailed: boolean, clearHistory: boolean): string {
  if (hasFailed) return "FAILED";
  if (cgpa <= 0) return "PASSED";
  if (cgpa >= 7.75 && clearHistory) return "First Class with Distinction";
  if (cgpa >= 6.75) return "First Class";
  if (cgpa >= 6.0) return "Second Class";
  if (cgpa >= 5.0) return "Pass Class";
  return "Not Eligible (CGPA below 5.00)";
}

function collegeName(code: string): string {
  return (colleges as Record<string, string>)[code] || code || "Unknown";
}

function branchOf(rollno: string): string {
  const key = (rollno || "").slice(6, 8);
  return (branches as Record<string, string>)[key] || "Unknown Branch";
}

function addHeader(doc: jsPDF, title: string, college: string, branch: string) {
  const W = doc.internal.pageSize.getWidth();
  doc.setFont("times", "bold");
  doc.setFontSize(11);
  doc.text("Jawaharlal Nehru Technological University Hyderabad", W / 2, 12, { align: "center" });
  doc.setFontSize(9);
  doc.text(title, W / 2, 18, { align: "center" });
  doc.setFont("times", "normal");
  doc.setFontSize(8);
  if (college) doc.text(college, W / 2, 23, { align: "center", maxWidth: W - 20 });
  if (branch) {
    doc.setFont("times", "bold");
    doc.text(branch.toUpperCase(), W / 2, 27, { align: "center" });
  }
}

function addStudentBlock(
  doc: jsPDF,
  startY: number,
  rows: Array<[string, string]>,
): number {
  autoTable(doc, {
    startY,
    body: rows.map(([k, v]) => [
      { content: k, styles: { fontStyle: "bold", fontSize: 7 } },
      { content: v || "-", styles: { fontSize: 7 } },
    ]),
    theme: "plain",
    styles: { cellPadding: 1.2 },
    columnStyles: { 0: { cellWidth: 32 }, 1: { cellWidth: "auto" } },
    margin: { left: 10, right: 10 },
  });
  return (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 4;
}

function subjectRows(result: Record<string, SubjectData>): string[][] {
  return Object.entries(result).map(([code, s], i) => [
    String(i + 1),
    code,
    s.name || "-",
    s.internal || "-",
    s.external || "-",
    s.total || "-",
    gradeOf(s.grade) + (s.rcrv ? " (RC)" : ""),
    s.credits || "-",
    isPass(s.grade) ? "PASS" : "FAIL",
  ]);
}

function addFooter(doc: jsPDF) {
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    const W = doc.internal.pageSize.getWidth();
    const H = doc.internal.pageSize.getHeight();
    doc.setFontSize(6);
    doc.setTextColor(140);
    doc.text(
      `Generated by jntuhresult — Not official. Verify with JNTUH. | Page ${i}/${pageCount}`,
      W / 2,
      H - 6,
      { align: "center" },
    );
    doc.setTextColor(0);
  }
}

// ---------- 1. Semester Memo (MM) : direct download ----------
export function downloadMmPdf(data: SemesterData, semester: string) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const d = data.Details;
  const rollno = d.Roll_No || "";
  addHeader(doc, `Marks Memo (MM) — ${SEM_LABEL[semester] || semester}`, collegeName(d.COLLEGE_CODE), branchOf(rollno));
  const y = addStudentBlock(doc, 30, [
    ["Hall Ticket No", rollno],
    ["Student Name", d.NAME || "-"],
    ["Father Name", d.FATHER_NAME || "-"],
    ["Semester", SEM_LABEL[semester] || semester],
  ]);
  autoTable(doc, {
    startY: y,
    head: [["S.No", "Code", "Subject", "Int", "Ext", "Total", "Grade", "Cred", "Result"]],
    body: subjectRows(data.Result),
    theme: "grid",
    styles: { fontSize: 7, cellPadding: 1.4 },
    headStyles: { fillColor: [30, 64, 175], textColor: 255, fontStyle: "bold" },
    columnStyles: {
      0: { cellWidth: 10 }, 1: { cellWidth: 20 }, 2: { cellWidth: "auto" },
      3: { cellWidth: 10 }, 4: { cellWidth: 10 }, 5: { cellWidth: 12 },
      6: { cellWidth: 14 }, 7: { cellWidth: 11 }, 8: { cellWidth: 14 },
    },
  });
  const fy = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 4;
  doc.setFontSize(9);
  doc.setFont("times", "bold");
  const sgpa = typeof data.SGPA === "number" ? data.SGPA.toFixed(2) : String(data.SGPA ?? "");
  doc.text(`SGPA: ${sgpa}`, 10, fy + 4);
  addFooter(doc);
  doc.save(`MM_${semester}_${rollno}.pdf`);
}

// ---------- 2. Consolidated Memo (CMM) : direct download, single-page year-wise layout ----------
// Mirrors cmm-memo Content: one combined table per year (left sem + right sem side-by-side).
export function downloadCmmPdf(data: AcademicData) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const d = data.Details;
  const rollno = d.Roll_No || "";
  const cgpaNum = typeof data.CGPA === "number" ? data.CGPA : parseFloat(String(data.CGPA)) || 0;

  addHeader(doc, "Consolidated Marks Memo (CMM)", collegeName(d.COLLEGE_CODE), branchOf(rollno));
  let y = addStudentBlock(doc, 30, [
    ["Hall Ticket No", rollno],
    ["Student Name", (d.NAME || "-").toUpperCase()],
    ["Father Name", (d.FATHER_NAME || "-").toUpperCase()],
  ]);

  const isLateral = rollno[4] === "5";
  const totalCredits = Object.values(data.Semesters || {}).reduce(
    (acc, sem) => acc + Object.values(sem.Result || {}).reduce((s, sub) => s + Number(sub.credits || 0), 0),
    0,
  );
  const hasFailed = Object.values(data.Semesters || {}).some((sem) =>
    Object.values(sem.Result || {}).some((sub) => {
      const g = gradeOf(sub.grade);
      return g === "F" || g === "AB";
    }),
  );
  const clearHistory = !Object.values(data.Semesters || {}).some((sem) =>
    (sem.History || []).some((h) => h.type === "supply"),
  );
  const award = getAwardClass(cgpaNum, hasFailed, clearHistory);

  for (const [s1, s2] of YEAR_SEMS) {
    const left = data.Semesters[s1];
    const right = data.Semesters[s2];
    if (!left && !right) {
      if (s1 === "1-1" && isLateral) {
        // Lateral blank year block
        if (y > 250) {
          doc.addPage();
          y = 12;
        }
        doc.setFillColor(243, 244, 246);
        doc.rect(10, y, W - 20, 6, "F");
        doc.setFont("times", "bold");
        doc.setFontSize(7);
        doc.text(YEAR_LABEL[s1[0]] || `${s1[0]} YEAR`, W / 2, y + 4, { align: "center" });
        y += 8;
        doc.setFontSize(7);
        doc.text("Directly admitted to second year", W / 2, y + 2, { align: "center" });
        y += 8;
        continue;
      }
      continue;
    }

    if (y > 250) {
      doc.addPage();
      y = 12;
    }
    // Year label bar
    doc.setFillColor(243, 244, 246);
    doc.rect(10, y, W - 20, 6, "F");
    doc.setFont("times", "bold");
    doc.setFontSize(7);
    doc.text(YEAR_LABEL[s1[0]] || `${s1[0]} YEAR`, W / 2, y + 4, { align: "center" });
    y += 6;

    const leftSubs = left ? Object.entries(left.Result || {}) : [];
    const rightSubs = right ? Object.entries(right.Result || {}) : [];
    const maxLen = Math.max(leftSubs.length, rightSubs.length);
    const body: string[][] = [];
    for (let i = 0; i < maxLen; i++) {
      const l = leftSubs[i];
      const r = rightSubs[i];
      body.push([
        l ? String(i + 1) : "",
        l ? `${l[1].name || "-"}${l[1].rcrv ? " (RC)" : ""}` : "",
        l ? l[1].internal || "-" : "",
        l ? l[1].external || "-" : "",
        l ? l[1].total || "-" : "",
        l ? gradeOf(l[1].grade) : "",
        l ? l[1].credits || "" : "",
        "",
        r ? String(i + 1) : "",
        r ? `${r[1].name || "-"}${r[1].rcrv ? " (RC)" : ""}` : "",
        r ? r[1].internal || "-" : "",
        r ? r[1].external || "-" : "",
        r ? r[1].total || "-" : "",
        r ? gradeOf(r[1].grade) : "",
        r ? r[1].credits || "" : "",
      ]);
    }

    const lShort = SEM_LABEL[s1] || s1;
    const rShort = SEM_LABEL[s2] || s2;
    autoTable(doc, {
      startY: y,
      head: [
        ["#", `${lShort} Subject`, "I", "E", "T", "G", "C", "", "#", `${rShort} Subject`, "I", "E", "T", "G", "C"],
      ],
      body,
      theme: "grid",
      styles: { fontSize: 6, cellPadding: 0.9, valign: "middle" },
      headStyles: { fillColor: [30, 64, 175], textColor: 255, fontStyle: "bold", fontSize: 6 },
      columnStyles: {
        0: { cellWidth: 7 }, 1: { cellWidth: 32 }, 2: { cellWidth: 8 }, 3: { cellWidth: 8 },
        4: { cellWidth: 9 }, 5: { cellWidth: 10 }, 6: { cellWidth: 8 }, 7: { cellWidth: 3 },
        8: { cellWidth: 7 }, 9: { cellWidth: 32 }, 10: { cellWidth: 8 }, 11: { cellWidth: 8 },
        12: { cellWidth: 9 }, 13: { cellWidth: 10 }, 14: { cellWidth: 8 },
      },
      margin: { left: 10, right: 10 },
    });
    y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 1.5;

    // SGPA strip for the year
    const sgpaParts: string[] = [];
    if (left && Number(left.SGPA) > 0) sgpaParts.push(`SGPA (${lShort}): ${Number(left.SGPA).toFixed(2)}`);
    if (right && Number(right.SGPA) > 0) sgpaParts.push(`SGPA (${rShort}): ${Number(right.SGPA).toFixed(2)}`);
    if (sgpaParts.length) {
      doc.setFont("times", "bold");
      doc.setFontSize(6.5);
      doc.text(sgpaParts.join("      "), W - 10, y + 2.5, { align: "right" });
      y += 5;
    } else {
      y += 2;
    }
  }

  // Totals + award bar
  if (y > 262) {
    doc.addPage();
    y = 12;
  }
  doc.setFont("times", "bold");
  doc.setFontSize(8);
  doc.text(`Total Credits: ${totalCredits}      CGPA: ${cgpaNum.toFixed(2)}      Award: ${award.toUpperCase()}`, 10, y + 3);
  y += 9;

  // Signature row
  doc.setFontSize(7);
  const sigY = Math.min(y + 12, 282);
  doc.text("Principal", 30, sigY, { align: "center" });
  doc.text("HOD", W / 2, sigY, { align: "center" });
  doc.text("Class Teacher", W - 30, sigY, { align: "center" });

  addFooter(doc);
  doc.save(`CMM_${rollno}.pdf`);
}

// ---------- 3. Full transcript (All Results) : direct download ----------
export function downloadTranscriptPdf(data: AllResultData) {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const d = data.Details;
  const rollno = d.Roll_No || "";
  addHeader(doc, "Academic History Report (All Results)", collegeName(d.COLLEGE_CODE), branchOf(rollno));
  let y = addStudentBlock(doc, 30, [
    ["Hall Ticket No", rollno],
    ["Student Name", d.NAME || "-"],
    ["Father Name", d.FATHER_NAME || "-"],
  ]);

  const keys = sortSemKeys(Object.keys(data.Results || {}));
  for (const sem of keys) {
    const exams = data.Results[sem] || [];
    for (const exam of exams) {
      if (y > 260) {
        doc.addPage();
        y = 12;
      }
      doc.setFont("times", "bold");
      doc.setFontSize(8);
      doc.text(`${sem} — Exam ${exam.exam_code} (${exam.type})`, 10, y);
      y += 2;
      autoTable(doc, {
        startY: y,
        head: [["S.No", "Code", "Subject", "Int", "Ext", "Total", "Grade", "Cred"]],
        body: Object.entries(exam.Result || {}).map(([code, sub], i) => [
          String(i + 1), code, sub.name || "-", sub.internal || "-", sub.external || "-",
          sub.total || "-", gradeOf(sub.grade), sub.credits || "-",
        ]),
        theme: "grid",
        styles: { fontSize: 6.5, cellPadding: 1.2 },
        headStyles: { fillColor: [5, 122, 85], textColor: 255, fontStyle: "bold" },
        columnStyles: {
          0: { cellWidth: 10 }, 1: { cellWidth: 19 }, 2: { cellWidth: "auto" },
          3: { cellWidth: 10 }, 4: { cellWidth: 10 }, 5: { cellWidth: 12 },
          6: { cellWidth: 15 }, 7: { cellWidth: 11 },
        },
      });
      y = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 5;
    }
  }
  addFooter(doc);
  doc.save(`Transcript_${rollno}.pdf`);
}
